import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const themes = JSON.parse(readFileSync(new URL("../design/themes.json", import.meta.url), "utf8"));
const selectors = {
  "living-light": ":root",
  "living-dark": 'html[data-theme="dark"]',
  "felled-light": 'html[data-timeline="felled"]',
  "felled-dark": 'html[data-timeline="felled"][data-theme="dark"]',
};
const palettes = Object.entries(themes).map(([name, tokens]) => `${selectors[name]} {\n  color-scheme: ${name.endsWith("dark") ? "dark" : "light"};\n${Object.entries(tokens).map(([key,value])=>`  --color-${key}: ${value};`).join("\n")}\n}`).join("\n\n");
const roles = readFileSync(new URL("../design/semantic-roles.css", import.meta.url),"utf8");
const css = `/* Generated by scripts/build-theme-tokens.mjs. Edit design/themes.json or design/semantic-roles.css. */\n${palettes}\n\n${roles}`;
const target = new URL("../app/theme.css",import.meta.url);
if(process.argv.includes("--check")) {
  if(readFileSync(target,"utf8")!==css) throw new Error("Theme CSS is out of date; run npm run themes:build.");
} else writeFileSync(fileURLToPath(target),css);
